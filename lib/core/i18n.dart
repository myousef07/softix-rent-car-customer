import 'package:flutter/foundation.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';

/// The app is written in Arabic. In English mode each phrase is swapped for its translation
/// below; `{0}`, `{1}`… stand for the values passed with it. Text from the company (names,
/// branches, cars) stays as entered.
class AppLanguage {
  AppLanguage._();

  static const supported = ['ar', 'en'];

  /// The chosen language; the app rebuilds when it changes.
  static final current = ValueNotifier<String>('ar');

  static bool get english => current.value == 'en';

  /// The other language's own name, for the switch: «English» / «العربية».
  static String get otherName => english ? 'العربية' : 'English';

  static const _storageKey = 'app_language';

  /// The language picked last time on this phone.
  static Future<void> restore([FlutterSecureStorage storage = const FlutterSecureStorage()]) async {
    try {
      final saved = await storage.read(key: _storageKey);
      if (saved != null && supported.contains(saved)) current.value = saved;
    } catch (_) {
      // No saved choice: Arabic.
    }
  }

  static Future<void> toggle([FlutterSecureStorage storage = const FlutterSecureStorage()]) async {
    current.value = english ? 'ar' : 'en';
    try {
      await storage.write(key: _storageKey, value: current.value);
    } catch (_) {
      // Kept for this session only.
    }
  }
}

String tr(String arabic, [List<Object?> values = const []]) {
  var text = AppLanguage.english ? (_english[arabic] ?? arabic) : arabic;
  for (var i = 0; i < values.length; i++) {
    text = text.replaceAll('{$i}', '${values[i] ?? ''}');
  }
  return text;
}

